#!/usr/bin/env bash
# Gate: every MCP tool schema that lives in the repo is a well-formed JSON
# Schema a model provider will accept (REQ-043, tool schema meta-validation).
#
# What it reads, and why that is the whole static surface:
#   * services/mcp/**/*.yaml — any `inputSchema` / `outputSchema` (or
#     `input_schema` / `output_schema`) declared in config. Today none is: every
#     server here lists its tools at runtime, so this scan guards future ones.
#   * tests/fixtures/mcp-tool-schemas/valid/*.json must pass and
#     invalid/*.json must each fail — proof the checker below still rejects
#     what providers refuse.
# The `systemprompt` server's tools are generated by schemars at compile time,
# so no shell gate can read them; tests/unit/mcp (systemprompt_tools.rs) runs
# the Rust checker (extensions/mcp/shared/src/tool_schema.rs) over them, and
# the server refuses to start on a violation.
#
# Checks (the same rules as the Rust checker): top-level `type: object`; a
# top-level `required` names only keys `properties` declares; no `$ref` that
# leaves the document. The full meta-schema check runs when the Python
# `jsonschema` module is installed and is skipped (with a note) otherwise —
# CI installs only python3, and the Rust checker always runs it in the tests.
# Portable: bash + python3 stdlib (PyYAML only when a services file declares a
# schema), identical on macOS and Linux.
set -uo pipefail
cd "$(dirname "$0")/.."

python3 - <<'PY'
import json
import pathlib
import sys

root = pathlib.Path(".")
KEYS = ("inputSchema", "outputSchema", "input_schema", "output_schema")
errors = []

try:
    import jsonschema  # type: ignore
except ImportError:
    jsonschema = None
    print("check-mcp-tool-schemas: python jsonschema not installed; meta-schema check left to the Rust tests")


def external_refs(node, out):
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str) and not value.startswith("#"):
                out.append(f"has a `$ref` to '{value}' outside the document")
            external_refs(value, out)
    elif isinstance(node, list):
        for item in node:
            external_refs(item, out)


def violations(schema):
    if not isinstance(schema, dict):
        return ["is not a JSON object"]
    out = []
    if jsonschema is not None:
        try:
            jsonschema.validators.validator_for(schema).check_schema(schema)
        except jsonschema.exceptions.SchemaError as e:
            out.append(f"violates the JSON Schema meta-schema: {e.message}")
    if schema.get("type") != "object":
        out.append("must declare top-level `type: object`")
    required = schema.get("required")
    if required is not None:
        props = schema.get("properties")
        if not isinstance(required, list):
            out.append("`required` must be an array")
        else:
            for name in required:
                if not isinstance(props, dict) or name not in props:
                    out.append(f"`required` names '{name}', which `properties` does not declare")
    external_refs(schema, out)
    return out


def find_schemas(node, trail, out):
    if isinstance(node, dict):
        for key, value in node.items():
            if key in KEYS:
                out.append((f"{trail}.{key}", value))
            else:
                find_schemas(value, f"{trail}.{key}", out)
    elif isinstance(node, list):
        for i, item in enumerate(node):
            find_schemas(item, f"{trail}[{i}]", out)


declared = 0
for path in sorted(root.glob("services/mcp/**/*.yaml")):
    text = path.read_text()
    if not any(k + ":" in text for k in KEYS):
        continue
    import yaml  # only needed when a services file declares a schema
    found = []
    find_schemas(yaml.safe_load(text) or {}, "", found)
    for where, schema in found:
        declared += 1
        for v in violations(schema):
            errors.append(f"{path}{where}: {v}")

fixtures = root / "tests/fixtures/mcp-tool-schemas"
for path in sorted((fixtures / "valid").glob("*.json")):
    for v in violations(json.loads(path.read_text())):
        errors.append(f"{path}: {v}")
invalid = sorted((fixtures / "invalid").glob("*.json"))
for path in invalid:
    found = violations(json.loads(path.read_text()))
    meta_only = path.name.startswith("meta-schema")
    if not found and not (meta_only and jsonschema is None):
        errors.append(f"{path}: expected a violation, the checker passed it")
if not invalid:
    errors.append(f"{fixtures}/invalid holds no fixtures; the checker is unproven")

if errors:
    print("\n".join(errors))
    print("mcp tool schemas FAILED")
    sys.exit(1)
print(f"mcp tool schemas OK ({declared} declared in services/mcp, fixtures proven)")
PY
