#!/usr/bin/env python3
"""Regenerate the vendor asset registration from services/web/vendor.yaml.

Writes extensions/web/shared/admin-core/src/vendor/assets.rs: one
AssetDefinition per manifest file, so a vendored file is published exactly
when the manifest lists it. `just vendor-add` calls this; the
vendor_allowlist test fails when the two disagree.
"""
import pathlib
import subprocess

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "services/web/vendor.yaml"
OUT = ROOT / "extensions/web/shared/admin-core/src/vendor/assets.rs"
CTOR = {"module": "js", "wasm": "wasm", "style": "css"}

packages = (yaml.safe_load(MANIFEST.read_text()) or {}).get("packages", [])
by_kind = {"module": [], "wasm": [], "style": []}
for pkg in packages:
    for f in pkg["files"]:
        by_kind[f["kind"]].append(f["path"])


def table(name, paths):
    rows = [f'    ("{p}", "js/vendor/{p}"),' for p in paths]
    return [f"const {name}: &[(&str, &str)] = &["] + rows + ["];", ""]


lines = [
    "//! Vendored third-party assets, one per file in `services/web/vendor.yaml`.",
    "//!",
    "//! GENERATED by `scripts/vendor-assets-rs.py` (run by `just vendor-add`);",
    "//! never edit by hand.",
    "",
    "use std::path::Path;",
    "",
    "use systemprompt::extension::AssetDefinition;",
    "",
]
lines += table("MODULES", by_kind["module"])
lines += table("WASM", by_kind["wasm"])
lines += table("STYLES", by_kind["style"])
lines += [
    "#[must_use]",
    "pub fn vendor_assets(storage_js: &Path) -> Vec<AssetDefinition> {",
    '    let vendor = storage_js.join("vendor");',
    "    let modules = MODULES.iter().map(|(src, dst)| AssetDefinition::js(vendor.join(src), dst));",
    "    let wasm = WASM.iter().map(|(src, dst)| AssetDefinition::wasm(vendor.join(src), dst));",
    "    let styles = STYLES.iter().map(|(src, dst)| AssetDefinition::css(vendor.join(src), dst));",
    "    modules.chain(wasm).chain(styles).collect()",
    "}",
    "",
]
OUT.write_text("\n".join(lines))
subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
